import { readdir, stat, mkdir, writeFile } from 'node:fs/promises'
import { extname, join, relative, sep } from 'node:path'
import sharp from 'sharp'

const publicRoot = join(process.cwd(), 'public')
const valid = new Set(['.jpg', '.jpeg', '.png', '.webp', '.avif'])

const numberOf = (name) => Number(name.match(/\d+/g)?.at(-1) ?? Number.MAX_SAFE_INTEGER)
const sequenceFolders = [
  'hero-frames-vertical',
  'hero-film-02-architecture',
  'hero-film-03-aerial',
  'hero-film-04-salon',
  'hero-film-05-courtyard',
  'hero-film-06-blue-hour',
  'hero-film-07-bedroom',
  'hero-film-08-primary-suite',
  'hero-film-09-craft',
  'hero-film-10-mediterranean-glide',
]
const variants = []

for (const [index, directory] of sequenceFolders.entries()) {
  const dir = join(publicRoot, 'optimized', directory)
  const entries = await readdir(dir, { withFileTypes: true })
  const images = entries
    .filter((entry) => entry.isFile() && valid.has(extname(entry.name).toLowerCase()) && !entry.name.includes('-mobile'))
    .sort((a, b) => numberOf(a.name) - numberOf(b.name) || a.name.localeCompare(b.name))
  if (!images.length) throw new Error(`No browser-readable frames found in public/${directory}.`)
  const urls = images.map((entry) => `/${relative(publicRoot, join(dir, entry.name)).split(sep).join('/')}`)
  const sizes = await Promise.all(images.map((entry) => stat(join(dir, entry.name))))
  const dimensions = await sharp(join(dir, images[0].name)).metadata()
  variants.push({
    id: String(index + 1),
    label: `Film ${String(index + 1).padStart(2, '0')}`,
    urls,
    mobileUrls: urls.map(url => url.replace('.webp', '-mobile.webp')),
    meta: {
      count: urls.length,
      directory,
      totalBytes: sizes.reduce((sum, item) => sum + item.size, 0),
      width: dimensions.width,
      height: dimensions.height,
    },
  })
}

const source = `// Generated by scripts/generate-frame-manifest.mjs\nexport const HERO_VARIANTS = ${JSON.stringify(variants, null, 2)} as const\nexport const FRAME_URLS = HERO_VARIANTS[0].urls\nexport const FRAME_META = HERO_VARIANTS[0].meta\n`
await mkdir(join(process.cwd(), 'src', 'lib'), { recursive: true })
await writeFile(join(process.cwd(), 'src', 'lib', 'frameManifest.generated.ts'), source)
console.log(`Detected ${variants.length} hero variations: ${variants.map((variant) => `${variant.meta.count} frames in public/${variant.meta.directory}`).join(', ')}`)
